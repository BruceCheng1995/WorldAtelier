import { buildSync,version as dependencyScannerVersion } from 'esbuild';
import { builtinModules } from 'node:module';
import { readFileSync,realpathSync } from 'node:fs';
import { resolve,relative,sep } from 'node:path';
import { hash } from './schema.mjs';

// assets.scene is injected into assembleProject, so its implementation is an
// explicit root rather than an import visible from project-snapshot alone.
const GENERATOR_ROOTS=['services/creation/project-snapshot.mjs','services/creation/assets.mjs'];
const BUILD_ROOTS=[...GENERATOR_ROOTS,'services/creation/export-builds.mjs','services/creation/build-worker.mjs','tools/canonical-game-web.mjs','tools/godot-web-compatibility.mjs'];
// Invoked by path rather than ESM import; a shared display build must never
// reuse a projection generated by different Godot baking code.
const BUILD_DATA_INPUTS=['tools/native-editor/bake_preview.gd','tools/linux-sandbox.c'];
/** Parse local ESM dependencies without executing modules. Native packages are
 * external; no filesystem walk can pull user data, tests or docs into a key. */
export function projectPolicyInventory(root,{generatorOnly=false}={}){
  const base=realpathSync(root),entryPoints=generatorOnly?GENERATOR_ROOTS:BUILD_ROOTS;
  const result=buildSync({absWorkingDir:base,entryPoints,bundle:true,write:false,metafile:true,outdir:'policy-scan-output',platform:'node',format:'esm',packages:'external',logLevel:'silent'});
  const builtins=new Set(builtinModules.map(name=>name.replace(/^node:/,'')));
  for(const input of Object.values(result.metafile.inputs))for(const dependency of input.imports)if(dependency.external&&dependency.path!=='esbuild'&&!builtins.has(dependency.path.replace(/^node:/,'')))throw Error('Game compiler external dependency needs an explicit identity: '+dependency.path);
  const dataInputs=generatorOnly?[]:BUILD_DATA_INPUTS;
  const files=[...new Set([...Object.keys(result.metafile.inputs),...dataInputs])].map(path=>{
    const actual=realpathSync(resolve(base,path)),local=relative(base,actual).split(sep).join('/');
    if(!actual.startsWith(base+sep)||! /^(services|packages|tools)\//.test(local)||local.split('/').some(part=>part.startsWith('.'))||! /\.(mjs|js|json)$/.test(local)&&!dataInputs.includes(local))throw Error('Game compiler dependency is outside the allowed source roots: '+local);
    const bytes=readFileSync(actual);return {path:local,sha256:hash(bytes),size:bytes.length};
  }).sort((a,b)=>a.path.localeCompare(b.path));
  const manifest={format:1,policy:'world-atelier-project-code-closure-v1',scanner:{name:'esbuild',version:dependencyScannerVersion},entry_points:entryPoints,files};
  return {...manifest,sha256:hash(manifest)};
}
